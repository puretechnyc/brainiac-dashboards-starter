// Writes db/d1-setup.sql: ONE file that creates the whole database on Cloudflare D1.
// It is built by applying schema.sql + every migration to an empty database and
// printing the result, so it always matches what the demo runs.
//   node --experimental-sqlite demo/export-schema.mjs
import { DatabaseSync } from 'node:sqlite';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const ROOT = new URL('..', import.meta.url).pathname;
const db = new DatabaseSync(':memory:');
db.exec(readFileSync(join(ROOT, 'schema.sql'), 'utf8'));
for (const f of readdirSync(join(ROOT, 'migrations')).sort()) {
  try { db.exec(readFileSync(join(ROOT, 'migrations', f), 'utf8')); } catch { /* already applied */ }
}
const rows = db.prepare(`SELECT type, name, sql FROM sqlite_master
  WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
  ORDER BY CASE type WHEN 'table' THEN 1 WHEN 'index' THEN 2 WHEN 'trigger' THEN 3 ELSE 4 END, rowid`).all();
let out = '-- Time tracker: full database setup for Cloudflare D1 (generated by demo/export-schema.mjs).\n';
for (const r of rows) out += r.sql.replace(/^CREATE (TABLE|INDEX|UNIQUE INDEX|TRIGGER) /, (m) => m + 'IF NOT EXISTS ') + ';\n';
const q = (v) => v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
for (const t of ['departments', 'app_settings']) {
  for (const row of db.prepare(`SELECT * FROM ${t}`).all()) {
    const cols = Object.keys(row);
    out += `INSERT OR IGNORE INTO ${t} (${cols.join(', ')}) VALUES (${cols.map((c) => q(row[c])).join(', ')});\n`;
  }
}
writeFileSync(join(ROOT, 'db', 'd1-setup.sql'), out);
console.log(`wrote db/d1-setup.sql (${rows.length} objects)`);
