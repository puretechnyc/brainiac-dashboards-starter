ALTER TABLE clients ADD COLUMN color TEXT
  CHECK (color IS NULL OR (length(color) = 7 AND substr(color, 1, 1) = '#' AND substr(color, 2) NOT GLOB '*[^0-9a-fA-F]*'));
UPDATE clients SET color = CASE ((SELECT COUNT(*) FROM clients c2 WHERE c2.rowid < clients.rowid) % 20)
  WHEN 0 THEN '#03A9F4' WHEN 1 THEN '#4CAF50' WHEN 2 THEN '#FF9800' WHEN 3 THEN '#F44336'
  WHEN 4 THEN '#9C27B0' WHEN 5 THEN '#E91E63' WHEN 6 THEN '#00BCD4' WHEN 7 THEN '#8BC34A'
  WHEN 8 THEN '#FFC107' WHEN 9 THEN '#795548' WHEN 10 THEN '#607D8B' WHEN 11 THEN '#3F51B5'
  WHEN 12 THEN '#009688' WHEN 13 THEN '#CDDC39' WHEN 14 THEN '#FF5722' WHEN 15 THEN '#673AB7'
  WHEN 16 THEN '#2196F3' WHEN 17 THEN '#FFEB3B' WHEN 18 THEN '#9E9E9E' ELSE '#E040FB' END
WHERE color IS NULL;
