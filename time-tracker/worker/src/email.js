const BREVO_ENDPOINT = "https://api.brevo.com/v3/smtp/email";
export function brevoConfigured(env) {
  return !!(env && env.BREVO_API_KEY);
}
export function emailVerifyEnabled(env) {
  const v = env && env.EMAIL_VERIFY_ENABLED;
  return v === true || v === "1" || v === "true";
}
async function brevoSend(env, { to, toName, subject, htmlContent }, fetchImpl = fetch) {
  if (!brevoConfigured(env)) {
    return { sent: false, stubbed: true, to };
  }
  const senderEmail = env && env.EMAIL_FROM || "no-reply@example.com";
  const senderName = env && env.EMAIL_FROM_NAME || "Time Tracker";
  try {
    const res = await fetchImpl(BREVO_ENDPOINT, {
      method: "POST",
      headers: {
        "api-key": env.BREVO_API_KEY,
        "Content-Type": "application/json",
        Accept: "application/json"
      },
      body: JSON.stringify({
        sender: { name: senderName, email: senderEmail },
        to: [{ email: to, name: toName || to }],
        subject,
        htmlContent
      })
    });
    return { sent: !!(res && res.ok), stubbed: false, to, status: res && res.status };
  } catch (e) {
    return { sent: false, stubbed: false, error: String(e && e.message || e), to };
  }
}
export async function sendVerificationEmail(env, { to, token, displayName }, fetchImpl = fetch) {
  const verifyUrl = `${env && env.APP_BASE_URL || ""}/api/auth/verify?token=${encodeURIComponent(token)}`;
  if (!emailVerifyEnabled(env)) {
    return { sent: false, stubbed: true, to, verifyUrl };
  }
  return brevoSend(env, {
    to,
    toName: displayName || to,
    subject: "Verify your Time Tracker account",
    htmlContent: `<p>Confirm your email to finish setting up Time Tracker.</p><p><a href="${verifyUrl}">Verify my email</a></p>`
  }, fetchImpl);
}
export async function sendInvoiceEmail(env, {
  recipientEmail,
  recipientName,
  invoiceNumber,
  totalFormatted,
  dueDate,
  periodStart,
  periodEnd,
  invoiceUrl
}, fetchImpl = fetch) {
  const dueLine = dueDate ? `<p><strong>Due:</strong> ${esc(dueDate)}</p>` : "";
  const htmlContent = `
    <div style="font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,sans-serif;max-width:600px;margin:0 auto">
      <h2 style="color:#2563eb">Invoice ${esc(invoiceNumber)}</h2>
      <p>Hello${recipientName ? " " + esc(recipientName) : ""},</p>
      <p>An invoice has been generated for your account.</p>
      <table style="border-collapse:collapse;width:100%;margin:16px 0">
        <tr><td style="padding:8px;border-bottom:1px solid #eee;font-weight:600">Invoice #</td><td style="padding:8px;border-bottom:1px solid #eee">${esc(invoiceNumber)}</td></tr>
        <tr><td style="padding:8px;border-bottom:1px solid #eee;font-weight:600">Period</td><td style="padding:8px;border-bottom:1px solid #eee">${esc(periodStart)} to ${esc(periodEnd)}</td></tr>
        <tr><td style="padding:8px;border-bottom:1px solid #eee;font-weight:600">Total</td><td style="padding:8px;border-bottom:1px solid #eee"><strong>${esc(totalFormatted)}</strong></td></tr>
      </table>
      ${dueLine}
      ${invoiceUrl ? `<p><a href="${esc(invoiceUrl)}" style="display:inline-block;padding:10px 24px;background:#2563eb;color:#fff;text-decoration:none;border-radius:6px;font-weight:600">View Invoice</a></p>` : ""}
      <p style="color:#666;font-size:13px;margin-top:24px">This invoice was generated by Time Tracker.<br/>Your Company</p>
    </div>
  `;
  return brevoSend(env, {
    to: recipientEmail,
    toName: recipientName || recipientEmail,
    subject: `Invoice ${invoiceNumber} from Your Company`,
    htmlContent
  }, fetchImpl);
}
